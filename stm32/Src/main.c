void check_uart_timeout(void) {

    if((HAL_GetTick() - last_rx_time) > MAX_UART_DOWNTIME_MS) {

        uart_parser_reset(&uart_parser);

        HAL_UART_DMAStop(&huart3);

        HAL_UARTEx_ReceiveToIdle_DMA(&huart3,UART3_rxBuffer,uart3_rx_len);

        __HAL_DMA_DISABLE_IT(huart3.hdmarx,DMA_IT_HT);

        comm_ctx.state = COMM_IDLE;

    }
}

